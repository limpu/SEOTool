// ─── Installation State (Web Installer — Stage 1) ─────────────────────────────

/**
 * Web Installer — the durable, server-side installation lock.
 *
 * THE POINT OF THIS TABLE: `/install` can create the first SUPER_ADMIN, so
 * once installation is complete it must become genuinely unreachable. That
 * decision has to live somewhere an attacker cannot reach and an accident
 * cannot clear. It is therefore NOT a frontend flag, NOT a cookie, NOT
 * localStorage, and NOT only a file on disk:
 *
 *  - a cookie/localStorage flag is client state — clearing it "reopens" the
 *    installer, which is an authentication bypass, not a UX quirk;
 *  - a marker FILE is ephemeral in a container (every redeploy wipes it) and
 *    deletable by anything with write access to the project directory.
 *
 * The database is the only store in this deployment that is durable across
 * redeploys, shared by every app replica, and already the authority for who
 * is an administrator. So the database is authoritative here too: deleting
 * `.install-token`, clearing cookies, wiping localStorage, or redeploying the
 * container all leave `completed = true` exactly where it was.
 *
 * SINGLETON. Exactly one row, `id = 1`, enforced by a CHECK constraint in the
 * migration. There is one installation per database; a second row would be a
 * second, contradictory answer to "is this platform installed", which is the
 * kind of ambiguity a security lock must not have.
 */
export const installationState = pgTable("installation_state", {
  /** Always 1. CHECK-constrained in SQL so the singleton is a DB invariant. */
  id: integer("id").primaryKey(),
  completed: boolean("completed").default(false).notNull(),
  completedAt: timestamp("completed_at"),
  /**
   * The first SUPER_ADMIN this installer created. `set null` on delete so
   * removing that user can never cascade the LOCK away — the installation
   * stays complete even if the account that completed it is later deleted.
   */
  completedByUserId: uuid("completed_by_user_id").references(() => users.id, {
    onDelete: "set null",
  }),
  /**
   * Per-step progress, so a partially-finished installation is resumable and
   * every step is idempotent (re-running a completed step is a no-op rather
   * than a duplicate write). Shape is owned by `src/lib/install/state.ts`.
   * NEVER holds a secret value — only step ids, statuses and timestamps.
   */
  steps: jsonb("steps").$type<Record<string, { status: string; at: string }>>().default({}).notNull(),
  /**
   * Short SHA-256 prefix of the install token currently in use. Recorded for
   * operator correlation only ("the token in the logs is the token on disk"),
   * and it is NOT what verification compares against — verification reads the
   * token file, precisely so it keeps working while the database is the thing
   * being repaired. Non-reversible; not a credential.
   */
  tokenFingerprint: varchar("token_fingerprint", { length: 64 }),
  createdAt: timestamp("created_at").defaultNow().notNull(),
  updatedAt: timestamp("updated_at").defaultNow().notNull(),
});
