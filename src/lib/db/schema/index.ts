// ─── Site-level file CONTENT: sitemaps + robots.txt (Phase 37) ───────────────
//
// Before Phase 37 the sitemap and robots.txt fetches happened inside the
// crawl, were handed to the rule engine, and were then DISCARDED — only the
// resulting `seo_issues` rows survived. That meant the Sitemap and Robots.txt
// reports could say "a sitemap was found" but could never show WHICH file, how
// many URLs it listed, or what it actually said. These two tables close that
// gap by persisting exactly what `llms_files` (Phase 18) already persisted for
// llms.txt: the fetch outcome plus the raw body, once per crawl run.
//
// A `manual` row (see `siteFileSourceEnum`) carries a NULL `crawl_run_id` — it
// is user-supplied, not crawl-derived, and is the only kind a user may delete.

export const sitemapDocuments = pgTable(
  "sitemap_documents",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    websiteId: uuid("website_id")
      .notNull()
      .references(() => websites.id, { onDelete: "cascade" }),
    crawlRunId: uuid("crawl_run_id").references(() => crawlRuns.id, { onDelete: "cascade" }),
    url: text("url").notNull(),
    kind: sitemapDocKindEnum("kind").notNull(),
    source: siteFileSourceEnum("source").default("discovered").notNull(),
    found: boolean("found").default(false).notNull(),
    httpStatus: integer("http_status"),
    /**
     * NULL for `kind = 'html'` ALWAYS — an HTML sitemap is a human-readable
     * page, not a machine-readable index, so this platform deliberately never
     * fetches its body. NULL therefore means "not fetched by design" for HTML
     * and "fetch produced no body" for XML; `fetchError`/`found` disambiguate.
     */
    rawContent: text("raw_content"),
    sizeBytes: integer("size_bytes"),
    /** Parsed `<url>` entries (urlset) or `<sitemap>` entries (index). NULL = not parsed. */
    urlCount: integer("url_count"),
    /** True when the document parsed as a `<sitemapindex>` rather than a `<urlset>`. */
    isIndex: boolean("is_index"),
    /**
     * The response exceeded `safeFetch`'s byte cap. `safeFetch` aborts rather
     * than returning a partial body, so a truncated row stores NO content —
     * the flag exists so the UI can say "too large to store" instead of
     * presenting an incomplete file as if it were whole.
     */
    truncated: boolean("truncated").default(false).notNull(),
    /** Verbatim reason a fetch did not produce a body (blocked address, timeout, size cap…). */
    fetchError: text("fetch_error"),
    fetchedAt: timestamp("fetched_at").defaultNow().notNull(),
  },
  (t) => [
    index("sitemap_documents_website_id_idx").on(t.websiteId),
    index("sitemap_documents_crawl_run_id_idx").on(t.crawlRunId),
  ]
);

