// ─── Crawl Runs ──────────────────────────────────────────────────────────────

export const crawlRuns = pgTable(
  "crawl_runs",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    websiteId: uuid("website_id")
      .notNull()
      .references(() => websites.id, { onDelete: "cascade" }),
    status: crawlStatusEnum("status").default("pending").notNull(),
    startedAt: timestamp("started_at"),
    completedAt: timestamp("completed_at"),
    pagesDiscovered: integer("pages_discovered").default(0),
    pagesCrawled: integer("pages_crawled").default(0),
    errors: jsonb("errors").$type<string[]>().default([]),
    createdAt: timestamp("created_at").defaultNow().notNull(),
  },
  (t) => [
    // At most one pending/running crawl per website — enforced at the DB
    // level (not just app-level check-then-insert) to close the race where
    // two "start crawl" requests land concurrently.
    uniqueIndex("crawl_runs_one_active_per_website")
      .on(t.websiteId)
      .where(sql`${t.status} IN ('pending', 'running')`),
    // Phase 33 — Performance Optimization: `computeWebsiteScores`/
    // `computeWebsiteRecommendations`/`computeWebsiteAiSearch`/
    // `computeWebsiteEeat`/report assembly (Phases 22/23/24/25/30) all run
    // `WHERE website_id = ? AND status = 'completed' ORDER BY created_at DESC
    // LIMIT 1` to find a website's latest completed crawl — a genuinely
    // common, hot query with no supporting index before this phase (the
    // unique index above only covers the pending/running partial case).
    // See read.md's Phase 33 write-up for the `EXPLAIN ANALYZE` before/after.
    index("crawl_runs_website_status_created_idx").on(t.websiteId, t.status, t.createdAt),
  ]
);

