/**
 * Phase 37 — reads and writes for stored site-level file content.
 *
 * READS are what the Sitemap / Robots.txt / AI Search report pages call. They
 * are plain SELECTs over already-persisted rows: opening a report NEVER causes
 * a third-party file to be fetched. A file is fetched during a crawl, or when
 * a user explicitly adds one by hand — nowhere else.
 *
 * WHICH ROWS COUNT. A crawl writes one `discovered` set per run, so a report
 * shows the set belonging to the most recent COMPLETED run (matching what the
 * rest of the module report already reads from). `manual` rows carry no crawl
 * run, are not regenerated by crawling, and are always shown.
 *
 * NOTHING here invents a value. A website with no completed crawl and no
 * manual entries yields empty arrays, which every caller renders as "never
 * checked" — distinct from a stored row whose `found` is false, which is a
 * real, measured absence.
 */

import { and, desc, eq, isNull, or } from "drizzle-orm";
import type { AnyPgColumn } from "drizzle-orm/pg-core";

import { db } from "@/lib/db";
import { crawlRuns, llmsFiles, robotsFiles, sitemapDocuments } from "@/lib/db/schema";
import { parseSitemapXml } from "@/lib/crawler/sitemap-parser";
import { parseLlmsTxt } from "@/lib/crawler/llms-txt-parser";
import { fetchSiteFile, isFetchable, type SiteFileType } from "./fetch";

export type SiteFileSource = "discovered" | "manual";

/** One stored file, in the shape the report cards render. */
export interface SiteFileEntry {
  id: string;
  type: SiteFileType;
  url: string;
  source: SiteFileSource;
  found: boolean;
  httpStatus: number | null;
  rawContent: string | null;
  sizeBytes: number | null;
  truncated: boolean;
  fetchError: string | null;
  fetchedAt: Date;
  /** XML sitemaps only. */
  urlCount: number | null;
  /** XML sitemaps only. */
  isIndex: boolean | null;
  /** llms.txt only — the already-parsed title, surfaced from Phase 18's stored row. */
  title: string | null;
}

/** The most recent COMPLETED crawl run for a website, or null. */
async function latestCompletedRunId(websiteId: string): Promise<string | null> {
  const [run] = await db
    .select({ id: crawlRuns.id })
    .from(crawlRuns)
    .where(and(eq(crawlRuns.websiteId, websiteId), eq(crawlRuns.status, "completed")))
    .orderBy(desc(crawlRuns.completedAt), desc(crawlRuns.createdAt))
    .limit(1);
  return run?.id ?? null;
}

/**
 * Matches rows belonging to the latest completed run OR to no run at all
 * (manual). When there is no completed run, only manual rows match.
 */
function runScope(runId: string | null, column: AnyPgColumn) {
  return runId ? or(eq(column, runId), isNull(column)) : isNull(column);
}

export async function listSitemapDocuments(websiteId: string): Promise<SiteFileEntry[]> {
  const runId = await latestCompletedRunId(websiteId);
  const rows = await db
    .select()
    .from(sitemapDocuments)
    .where(and(eq(sitemapDocuments.websiteId, websiteId), runScope(runId, sitemapDocuments.crawlRunId)))
    .orderBy(desc(sitemapDocuments.fetchedAt));

  return rows.map((row) => ({
    id: row.id,
    type: row.kind === "html" ? ("sitemap_html" as const) : ("sitemap_xml" as const),
    url: row.url,
    source: row.source,
    found: row.found,
    httpStatus: row.httpStatus,
    rawContent: row.rawContent,
    sizeBytes: row.sizeBytes,
    truncated: row.truncated,
    fetchError: row.fetchError,
    fetchedAt: row.fetchedAt,
    urlCount: row.urlCount,
    isIndex: row.isIndex,
    title: null,
  }));
}

